func TestInvestigatorScope(t *testing.T) {
	for _, name := range []string{"sre-k8s-investigator", "sre-metrics-analyst", "sre-logs-investigator", "sre-change-historian", "sre-trace-analyst", "sre-eks-investigator", "sre-gke-investigator"} {
		for _, agent := range []string{name, "sre-agent:" + name, "other:plugin:" + name} {
			got := Check(Event{Agent: agent, Tool: "Bash", Input: json.RawMessage(`{"command":"rm x"}`)})
			if !got.Block || got.Reason != "rm isn't on the read-only list" {
				t.Fatalf("%s: %#v", agent, got)
			}
		}
	}
	for _, agent := range []string{"", "general-purpose", "my-sre-k8s-investigator", "sre-k8s-investigator:other", "sre-k8s-investigator-extra"} {
		if got := Check(Event{Agent: agent, Tool: "Bash", Input: json.RawMessage(`42`)}); got.Block {
			t.Fatalf("%s: %#v", agent, got)
		}
	}
}

func TestRelevantInputs(t *testing.T) {
	for _, tc := range []struct{ tool, input, reason string }{
		{"Bash", `{"Command":"echo x"}`, "the guard couldn't read the Bash command"},
		{"Bash", `{"command":null}`, "the guard couldn't read the Bash command"},
		{"Bash", `{"command":123}`, "the guard couldn't read the Bash command"},
		{"Bash", `{"command":[]}`, "the guard couldn't read the Bash command"},
		{"Bash", `false`, "the guard couldn't read the Bash command"},
		{"Bash", `{"command":"echo hello","ignored":{"command":"rm x"}}`, ""},
		{"Read", `{"file_path":"/home/u/.docker/config.json"}`, "it reads a credential file"},
		{"Grep", `{"path":".git-credentials"}`, "it reads a credential file"},
		{"Read", `{"file_path":"/repo/README.md","path":".aws/credentials"}`, ""},
		{"Grep", `{"path":"/repo","file_path":".aws/credentials"}`, ""},
		{"Read", `null`, ""},
		{"Grep", `{}`, ""},
		{"Read", `[]`, "the guard couldn't read the tool input"},
		{"Grep", `{"path":{}}`, "the guard couldn't read the tool path"},
		{"Glob", `42`, ""},
	} {
		t.Run(tc.tool+tc.input, func(t *testing.T) {
			got := Check(Event{Agent: "sre-k8s-investigator", Tool: tc.tool, Input: json.RawMessage(tc.input)})
			if got.Reason != tc.reason || got.Block != (tc.reason != "") {
				t.Fatalf("got %#v, want %q", got, tc.reason)
			}
		})
	}
}

